#!/usr/bin/env python3
"""Dry run for P47/P48/P49 (decided by Jason, 2026-10-21). Writes reports/support_dryrun.md and
reports/deepening_queue.md. Changes no record and no chart.

  python3 scripts/support_dryrun.py [--before REV]   # REV: the commit to compare dot levels against (default HEAD)
"""
import argparse, os, subprocess, sys, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import yaml  # noqa: E402
from lib.records import REPO, read_record, person_files, support_level, point_level  # noqa: E402

PROPOSED_SQ = [  # (test, label) for the dry run only; the relabel step sets source_quality by hand-checked rules
    (lambda s: "roster" in (s.get("citation") or "").lower() and "Genius Study" in (s.get("author") or ""), "study roster"),
    (lambda s: "unofficial" in (s.get("reliability_note") or "").lower() or "wikisource" in (s.get("url") or "").lower(), "unofficial web copy"),
    (lambda s: "ocr" in (s.get("reliability_note") or "").lower(), "archive scan (OCR only)"),
    (lambda s: "interview" in (s.get("kind") or "").lower() or "newspaper" in (s.get("kind") or "").lower(), "newspaper interview"),
    (lambda s: s.get("type") == "primary", "primary / own words"),
    (lambda s: s.get("type") == "tertiary" or "encyclopedia" in (s.get("kind") or "").lower(), "reference entry"),
    (lambda s: s.get("type") == "secondary", "scholarly edition or monograph"),
]


def proposed_sq(s):
    for t, lab in PROPOSED_SQ:
        try:
            if t(s):
                return lab
        except Exception:  # noqa: BLE001
            pass
    return "other"


def old_level(a, b):
    """Pre-P48 chart: faded when either certainty < 0.7, else dark."""
    return "faded" if min(a.get("certainty") or 0, b.get("certainty") or 0) < 0.7 else "solid"


def scored(c):
    return isinstance((c or {}).get("value"), int) and not isinstance(c.get("value"), bool)


def load_before(rev, rel):
    try:
        txt = subprocess.check_output(["git", "-C", REPO, "show", f"{rev}:{rel}"], stderr=subprocess.DEVNULL, text=True)
    except subprocess.CalledProcessError:
        return None
    return yaml.safe_load(txt.split("---")[1])


def fmt(c):
    v = (c or {}).get("value")
    if scored(c):
        return f"{v} @{c.get('certainty')}"
    return str(v)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--before", default="HEAD")
    a = ap.parse_args()
    rows, sqc = [], collections.Counter()
    for f in person_files():
        d, _ = read_record(f)
        rel = os.path.relpath(f, REPO).replace(os.sep, "/")
        ident = d["identity"]; ro = ident["roster"]
        lio = d["worldview"]["lio_axes"]; A, B = lio["A_locus"], lio["B_cause"]
        srcs = [s for s in d.get("sources") or []]
        labs = [proposed_sq(s) for s in srcs]
        sqc.update(labs)
        nsrc = sum(1 for l in labs if l != "study roster")
        new = point_level(A, B)
        bd = load_before(a.before, rel)
        if bd:
            bA, bB = bd["worldview"]["lio_axes"]["A_locus"], bd["worldview"]["lio_axes"]["B_cause"]
            was = old_level(bA, bB) if scored(bA) and scored(bB) else None
        else:
            was = None
        rows.append(dict(name=ident["display_name"], F=ro["F"], rank=ro["rank"], status=ro["status"], nsrc=nsrc,
                         A=fmt(A), B=fmt(B), sA=support_level(A), sB=support_level(B), was=was, new=new,
                         labs=collections.Counter(labs)))
    rows.sort(key=lambda r: (-r["F"], r["rank"]))
    newly = [r for r in rows if r["new"] and not r["was"]]
    dropped = [r for r in rows if r["was"] and not r["new"]]
    changed = [r for r in rows if r["was"] and r["new"] and r["was"] != r["new"]]
    plotted = [r for r in rows if r["new"]]
    lv = collections.Counter(r["new"] for r in plotted)
    ax = collections.Counter(x for r in rows for x in (r["sA"], r["sB"]) if x)
    core = [r for r in rows if r["status"] == "core"]
    out = ["# Support-level dry run (P47, P48, P49)", "",
           f"Generated by scripts/support_dryrun.py against `{a.before}` for the before state. Dry run only: no record "
           "is relabelled and no chart is regenerated. Support levels follow P48 (`support_level()` in scripts/lib/records.py); "
           "the old chart had two levels (dark when both certainties ≥ 0.7, else faded). Proposed source_quality labels are "
           "a keyword mapping from type/kind/reliability_note and are for sizing only.", "",
           "## Totals", "",
           f"- Records: {len(rows)} ({len(core)} core; P50 freezes the study at the coded core people).",
           f"- Plotted under P48: {len(plotted)} (solid {lv['solid']}, faded {lv['faded']}, single {lv['single']}).",
           f"- Scored axes by support level (A and B): solid {ax['solid']}, faded {ax['faded']}, single {ax['single']}.",
           f"- Newly plotted vs `{a.before}`: {', '.join(r['name'] for r in newly) or 'none'}.",
           f"- No longer plotted: {', '.join(r['name'] for r in dropped) or 'none'}.",
           f"- Dot level changes: {len(changed)} people (" + ", ".join(f"{k[0]}→{k[1]} {v}" for k, v in collections.Counter((r['was'], r['new']) for r in changed).items()) + ").",
           "- Proposed source_quality across all sources: " + ", ".join(f"{k} {v}" for k, v in sqc.most_common()) + ".", "",
           "## People who change dot level", "", "| person | before | after | A | A support | B | B support |", "|---|---|---|---|---|---|---|"]
    out += [f"| {r['name']} | {r['was']} | {r['new']} | {r['A']} | {r['sA']} | {r['B']} | {r['sB']} |" for r in changed]
    out += ["", "## Every record", "", "Order: F descending, then roster rank.", "",
            "| rank | F | person | sources (excl. roster) | A | A support | B | B support | dot before | dot after |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    out += [f"| {r['rank']} | {r['F']} | {r['name']} | {r['nsrc']} | {r['A']} | {r['sA'] or '—'} | {r['B']} | {r['sB'] or '—'} | {r['was'] or '—'} | {r['new'] or '—'} |" for r in rows]
    open(os.path.join(REPO, "reports", "support_dryrun.md"), "w").write("\n".join(out) + "\n")

    def need(r):
        n = []
        for k in ("A", "B"):
            s = r["s" + k]
            if s is None:
                n.append(f"{k} {r[k]}")
            elif s != "solid":
                n.append(f"{k} {s}")
        if r["nsrc"] < 2:
            n.append(f"{r['nsrc']} source")
        return "; ".join(n) or "solid on A and B"
    q = ["# Deepening queue (P50)", "", "The 215-person frozen core, ordered by F descending, then roster rank (P32 order). "
         "'needs' lists the axes that are unscored or not yet solid and records with fewer than two sources. "
         "Generated by scripts/support_dryrun.py; nothing here has been worked yet.", "",
         "| # | rank | F | person | sources | A | B | needs |", "|---|---|---|---|---|---|---|---|"]
    q += [f"| {i} | {r['rank']} | {r['F']} | {r['name']} | {r['nsrc']} | {r['A']} | {r['B']} | {need(r)} |" for i, r in enumerate(core, 1)]
    open(os.path.join(REPO, "reports", "deepening_queue.md"), "w").write("\n".join(q) + "\n")
    print(f"{len(rows)} records, {len(core)} core, {len(plotted)} plotted; newly {[r['name'] for r in newly]}; "
          f"level changes {len(changed)}; levels {dict(lv)}")


if __name__ == "__main__":
    main()
